export const RESIDUO_POR_ID = Object.fromEntries(RESIDUOS.map((r) => [r.id, r]));

export function barajar(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Elige `n` residuos al azar de un tacho, filtrando por dificultades permitidas. */
export function elegir(tacho, n, dificultades = [1, 2, 3]) {
  return barajar(
    RESIDUOS.filter((r) => r.tacho === tacho && dificultades.includes(r.dificultad)),
  ).slice(0, n);
}
